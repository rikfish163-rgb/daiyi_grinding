#!/usr/bin/env python3
"""Audit exported casting geometry, RGB-D units and evaluator isolation."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from xml.etree import ElementTree

import numpy as np
import trimesh
from scipy.spatial import cKDTree

from daiyi_grinding import casting_synthesis
from daiyi_grinding.cad_defects import DEFAULT_MESH
from daiyi_grinding.team_data_reuse import sha256
from daiyi_grinding.workstation_model import source_hashes, write_json

PUBLIC_FIELDS = {
    "rgb",
    "depth",
    "reference_depth",
    "K",
    "T_workpiece_camera",
    "T_world_camera",
    "T_world_workpiece",
    "encoder_angle_deg",
    "synthetic_noise_sigma_mm",
    "synthetic_dropout_probability",
}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def root_distance_mm(mesh, roots):
    # Bound temporary point/triangle arrays for the supplied CAD.
    return max(
        float(trimesh.proximity.closest_point_naive(mesh, part)[1].max()) * 1000
        for part in np.array_split(roots, max(1, int(np.ceil(len(roots) / 32))))
    )


def audit(folder, frozen_generation=False):
    manifest = json.loads((folder / "manifest.json").read_text())
    protocol = manifest["protocol"]
    expected_hashes = {
        **source_hashes(),
        "casting_synthesis.py": sha256(casting_synthesis.__file__),
    }
    if frozen_generation:
        # Training data may legitimately predate the inference implementation.
        # Verify every recorded generator/config snapshot and unchanged CAD
        # asset instead of silently relabeling it as generated by new code.
        for name, digest in protocol["source_hashes"].items():
            snapshot = folder / "source_snapshot" / name
            actual = (
                sha256(snapshot)
                if snapshot.is_file()
                else expected_hashes.get(name)
            )
            require(
                actual == digest, f"Frozen generation hash mismatch: {name}"
            )
    else:
        require(
            protocol["source_hashes"] == expected_hashes, "Source hash mismatch"
        )
    require(
        protocol["real_scans_used"] is False
        and protocol["trained_model_used"] is False,
        "Incorrect real-data/model provenance",
    )
    profile = protocol["profile"]
    require(not profile["real_scan_fitted"], "This is a prior, not a scan fit")
    nominal = trimesh.load_mesh(DEFAULT_MESH, process=True)
    counts = dict(
        episodes=0,
        views=0,
        objects=0,
        fragments=0,
        visible_objects=0,
        root_samples=0,
        depth_consistent_root_samples=0,
        adapted_clouds_executed=0,
        adapted_clouds_empty=0,
        normal_false_positive_pixels=0,
        normal_predicted_paths=0,
    )
    fixed_camera = None
    appearance_by_seed = {}
    maximum_root_distance = maximum_cloud_error = 0.0
    macro_pixels, noise_measurements, per_sample = [], [], []
    for sample in manifest["samples"]:
        directory = folder / sample["sample_directory"]
        require(
            sample["casting_profile"] == profile["profile"], "Profile mismatch"
        )
        require(sample["view_count"] == 6, "Expected six encoder views")
        appearance = sample["appearance"]
        seed = sample["seed"]
        if seed in appearance_by_seed:
            require(
                appearance_by_seed[seed] == appearance, "Class-coded appearance"
            )
        appearance_by_seed[seed] = appearance
        geometry = ElementTree.parse(directory / "scene.xml")
        materials = {
            item.get("material")
            for item in geometry.findall(".//geom")
            if item.get("name", "").startswith(("wp_", "added_defect_"))
            and item.get("group") in {"1", "4"}
        }
        require(
            len(materials) == 1 and None not in materials, "Different materials"
        )
        counts["episodes"] += 1
        counts["objects"] += len(sample["objects"])
        counts["visible_objects"] += sample["visible_objects"]
        counts["root_samples"] += sample["root_points"]
        counts["depth_consistent_root_samples"] += sample[
            "root_points_depth_consistent_some_view"
        ]
        for identity, obj in enumerate(sample["objects"], 1):
            metadata = json.loads(
                (
                    directory / "evaluator" / f"object_{identity:02d}.json"
                ).read_text()
            )
            solid = trimesh.load_mesh(
                directory / f"{obj['geom']}.stl", process=True
            )
            require(
                solid.is_watertight
                and solid.is_winding_consistent
                and solid.volume > 0,
                "Invalid exported solid",
            )
            pieces = solid.split(only_watertight=False)
            require(
                len(pieces) == len(metadata["root_curves_m"]),
                "Fragment mismatch",
            )
            for piece in pieces:
                require(
                    piece.is_watertight
                    and piece.is_winding_consistent
                    and piece.volume > 0,
                    "Invalid fragment",
                )
            counts["fragments"] += len(pieces)
            for root in metadata["root_curves_m"]:
                distance = root_distance_mm(nominal, np.asarray(root))
                require(distance < 0.01, "Root is unsupported by original CAD")
                maximum_root_distance = max(maximum_root_distance, distance)
            signed = np.einsum(
                "ij,ij->i",
                np.asarray(metadata["original_vertices"])
                - np.asarray(metadata["base_vertices"]),
                np.asarray(metadata["vertex_normals"]),
            )
            require(signed.min() < -0.00002, "No embedded root")
            # Verify every separate fragment, rather than just the combined mesh.
            vertices = np.asarray(metadata["original_vertices"])
            vertex_tree = cKDTree(vertices)
            for piece in pieces:
                nearest = vertex_tree.query(piece.vertices)[1]
                require(
                    signed[nearest].min() < -0.00002,
                    "A fragment has no embedded root",
                )
            source = metadata["parameters"].get("compact_prior_instance")
            if source is not None:
                require(
                    source["optimizer_split"] == "train", "Holdout fit leakage"
                )
                require(
                    source["semantic_code"] == 602,
                    "Wrong compact semantic scope",
                )
                require(
                    abs(metadata["height_peak_mm"] - source["height_mm"])
                    < 1e-5,
                    "Transferred visible height differs from the source",
                )
            macro_pixels.append(
                obj["macro_validation"]["defect_visible_pixels"]
            )
        for index in range(6):
            counts["views"] += 1
            with np.load(
                directory / "public" / f"view_{index:02d}.npz"
            ) as arrays:
                require(
                    set(arrays.files) == PUBLIC_FIELDS, "Labels in public RGB-D"
                )
                raw = {key: arrays[key] for key in arrays.files}
            with np.load(
                directory / "evaluator" / f"view_{index:02d}_labels.npz"
            ) as labels:
                ideal = labels["ideal_depth_m"]
                semantic = labels["semantic"]
            require(
                raw["rgb"].shape[:2] == raw["depth"].shape == semantic.shape,
                "Image shape mismatch",
            )
            require(
                set(np.unique(semantic)).issubset({0, 1, 2, 3}),
                "Semantic codes",
            )
            camera = raw["T_world_camera"]
            if fixed_camera is None:
                fixed_camera = camera
            require(
                np.allclose(camera, fixed_camera, atol=1e-12), "Moving camera"
            )
            require(
                np.allclose(
                    raw["T_world_workpiece"] @ raw["T_workpiece_camera"],
                    camera,
                    atol=1e-10,
                ),
                "World/workpiece camera transform mismatch",
            )
            require(
                abs(float(raw["encoder_angle_deg"]) - index * 60) < 0.01,
                "Encoder did not attain the commanded angle",
            )
            paired = (
                np.isfinite(raw["depth"]) & np.isfinite(ideal) & (ideal > 0)
            )
            differences = (raw["depth"][paired] - ideal[paired]) * 1000
            sigma = float(
                np.median(np.abs(differences - np.median(differences)))
                / 0.67448975
            )
            expected_sigma = float(raw["synthetic_noise_sigma_mm"])
            require(
                abs(sigma - expected_sigma) < 0.005,
                "Depth noise units mismatch",
            )
            noise_measurements.append(sigma)
            cloud_file = (
                directory / "public" / f"view_{index:02d}_weldgrind_cloud.npz"
            )
            if cloud_file.is_file():
                metadata = json.loads(
                    cloud_file.with_suffix(".json").read_text()
                )
                require(
                    not metadata["gt_defect_or_instance_labels_read"]
                    and not metadata["sam_model_executed"],
                    "Cloud provenance mismatch",
                )
                with np.load(cloud_file) as arrays:
                    require(
                        str(arrays["units"].item()) == "mm",
                        "Cloud units mismatch",
                    )
                    require(
                        str(arrays["roi_source"].item())
                        == "geometric_reference_detector",
                        "Wrong candidate source",
                    )
                    points = arrays["points"][:, :3]
                    pixels = arrays["point_uv"]
                if not metadata["adapter_executed"]:
                    require(
                        len(points) == 0, "Invented normal/empty ROI points"
                    )
                    counts["adapted_clouds_empty"] += 1
                else:
                    counts["adapted_clouds_executed"] += 1
                    u, v = pixels.T
                    depth = raw["depth"][v, u].astype(float) * 1000
                    k = raw["K"]
                    camera_xyz = np.column_stack(
                        [
                            (u - k[0, 2]) * depth / k[0, 0],
                            (v - k[1, 2]) * depth / k[1, 1],
                            depth,
                        ]
                    )
                    expected = (
                        camera_xyz @ camera[:3, :3].T + camera[:3, 3] * 1000
                    )
                    error = float(
                        np.linalg.norm(expected - points, axis=1).max()
                    )
                    require(
                        error < 0.002,
                        "Backprojection frame/pixel/units mismatch",
                    )
                    maximum_cloud_error = max(maximum_cloud_error, error)
            if sample["case"] == "casting_normal":
                require(
                    not np.isin(semantic, [1, 2]).any(),
                    "Defects in normal control",
                )
        if sample["case"] == "casting_normal":
            counts["normal_false_positive_pixels"] += sample[
                "legacy_detector_metrics"
            ]["fp"]
            counts["normal_predicted_paths"] += sample["legacy_predicted_paths"]
        detections = json.loads((directory / "detections.json").read_text())
        per_sample.append(
            dict(
                case=sample["case"],
                seed=seed,
                counts_by_predicted_kind={
                    kind: sum(item["kind"] == kind for item in detections)
                    for kind in ("seam", "burr", "review", "preserve")
                },
                f1=sample["legacy_detector_metrics"]["f1"],
                predicted_paths=sample["legacy_predicted_paths"],
            )
        )
    require(
        counts["normal_false_positive_pixels"]
        == counts["normal_predicted_paths"]
        == 0,
        "Normal control regression",
    )
    return {
        "passed": True,
        "profile": profile["profile"],
        "counts": counts,
        "source_hashes_match": True,
        "hash_scope": "recorded frozen generation snapshots and unchanged CAD"
        if frozen_generation
        else "current generation code",
        "raw_labels_isolated": True,
        "shared_materials_verified": True,
        "fixed_camera_and_integrated_encoder_verified": True,
        "root_to_original_CAD_max_mm": maximum_root_distance,
        "backprojection_numeric_max_mm": maximum_cloud_error,
        "macro_min_visible_pixels": min(macro_pixels),
        "depth_noise_mad_sigma_mm_range": [
            min(noise_measurements),
            max(noise_measurements),
        ],
        "source_kind": "team synthetic prior; real 097 scan not obtained",
        "metric_scope": "synthetic file, geometry and numerical checks; no real metrology",
        "samples": per_sample,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path)
    parser.add_argument("--frozen-generation", action="store_true")
    args = parser.parse_args()
    result = audit(args.dataset.resolve(), args.frozen_generation)
    write_json(args.dataset / "validation.json", result)
    print(
        json.dumps(
            {key: value for key, value in result.items() if key != "samples"}
        )
    )


if __name__ == "__main__":
    main()
